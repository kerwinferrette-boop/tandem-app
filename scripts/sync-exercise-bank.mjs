// EPIC-031 Phase 2b — EXERCISE_BANK → exercises seed generator
// Extracts EXERCISE_BANK LIVE from programs.js (source-first: never a copied
// list) and emits migrations/epic031_exercises_seed.sql as idempotent upserts
// keyed on slug. Re-run after any bank edit; commit the regenerated SQL.
//
// EPIC-026 tags (movement_pattern/unilateral/complexity/position_bias) are
// intentionally NOT emitted — no source names them yet; they stay NULL
// (DOCTRINE: flag a gap, never fabricate).
//
// Usage: node scripts/sync-exercise-bank.mjs
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(root, 'programs.js'), 'utf8');

const ctx = { window: {}, document: { querySelectorAll: () => [] },
              localStorage: { getItem: () => null, setItem: () => {} } };
vm.createContext(ctx);
vm.runInContext(src + ';globalThis.__BANK = EXERCISE_BANK;', ctx);
const bank = ctx.__BANK;
const slugs = Object.keys(bank);
if (slugs.length < 100) throw new Error(`Bank suspiciously small (${slugs.length}) — extraction broken?`);

const q = (s) => s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${(a || []).map(q).join(',')}]::text[]`;
const num = (n) => (n == null || !Number.isFinite(Number(n))) ? 'null' : String(n);

const ALLOWED_EQ = new Set(['barbell','dumbbell','cable','machine','bodyweight','band']);
const ALLOWED_TIER = new Set(['home','hotel_gym','full_gym']);
const ALLOWED_CAT = new Set(['compound','isolation','core','cardio']);
const ALLOWED_UNIT = new Set(['reps','sec','bw']);

const rows = [];
for (const slug of slugs) {
  const e = bank[slug];
  // Validate against the table's CHECK constraints BEFORE emitting — fail loud
  // here rather than at apply time.
  if (!ALLOWED_TIER.has(e.tier)) throw new Error(`${slug}: bad tier ${e.tier}`);
  if (!ALLOWED_CAT.has(e.category)) throw new Error(`${slug}: bad category ${e.category}`);
  if (e.equipment != null && !ALLOWED_EQ.has(e.equipment)) throw new Error(`${slug}: bad equipment ${e.equipment}`);
  const unit = e.unit || 'reps';
  if (!ALLOWED_UNIT.has(unit)) throw new Error(`${slug}: bad unit ${unit}`);

  rows.push(`(${q(slug)}, ${q(e.name)}, ${q(e.tier)}, ${q(e.category)}, ` +
    `${arr(e.muscleGroups?.primary)}, ${arr(e.muscleGroups?.secondary)}, ${arr(e.emphasis)}, ` +
    `${num(e.oneRmFactor)}, ${q(unit)}, ${num(e.secs)}, ${q(e.videoId)}, ` +
    `${q(e.why)}, ${arr(e.cues)}, ${q(e.equipment)})`);
}

const sql = `-- ============================================================================
-- EPIC-031 — exercises seed (GENERATED FILE — do not hand-edit)
-- Generated by scripts/sync-exercise-bank.mjs from programs.js EXERCISE_BANK
-- Generated: ${new Date().toISOString()} · entries: ${rows.length}
-- Idempotent: upsert on slug. EPIC-026 tag columns left NULL by design.
-- DO NOT apply to live Supabase before Kerwin's SQL review.
-- ============================================================================
insert into public.exercises
  (slug, name, tier, category, muscle_primary, muscle_secondary, emphasis,
   one_rm_factor, unit, secs, video_id, why, cues, equipment)
values
${rows.join(',\n')}
on conflict (slug) do update set
  name = excluded.name,
  tier = excluded.tier,
  category = excluded.category,
  muscle_primary = excluded.muscle_primary,
  muscle_secondary = excluded.muscle_secondary,
  emphasis = excluded.emphasis,
  one_rm_factor = excluded.one_rm_factor,
  unit = excluded.unit,
  secs = excluded.secs,
  video_id = excluded.video_id,
  why = excluded.why,
  cues = excluded.cues,
  equipment = excluded.equipment;
`;

const out = path.join(root, 'migrations', 'epic031_exercises_seed.sql');
fs.writeFileSync(out, sql);
console.log(`Wrote ${out} — ${rows.length} exercises upserted on slug.`);
